/** Yazı tipinde karşılığı olmayan karakterler için kullanılır. */
const FALLBACK = GLYPHS["?"]!;

/** Metni Türkçe kurallarına göre büyük harfe çevirir (i → İ, ı → I). */
export function toDisplayCase(text: string): string {
  return text.toLocaleUpperCase("tr-TR");
}

/** Bir karakterin satırlarını döndürür; bilinmeyen karakterler "?" olarak görünür. */
export function glyphFor(char: string): string[] {
  return GLYPHS[toDisplayCase(char)] ?? FALLBACK;
}

/** Yazı tipinin desteklediği karakter mi? */
export function isSupported(char: string): boolean {
  return toDisplayCase(char) in GLYPHS;
}

/**
 * Metni nokta sütunlarına çevirir. Dönen dizinin her elemanı bir sütundur
 * ve yukarıdan aşağıya GLYPH_HEIGHT adet "yanıyor mu" bilgisi içerir.
 */
export function textToColumns(text: string): boolean[][] {
  const columns: boolean[][] = [];
  const chars = Array.from(toDisplayCase(text));
  chars.forEach((char, index) => {
    const rows = glyphFor(char);
    for (let x = 0; x < GLYPH_WIDTH; x++) {
      columns.push(rows.map((row) => row[x] === "#"));
    }
    if (index < chars.length - 1) {
      for (let s = 0; s < GLYPH_SPACING; s++) {
        columns.push(new Array<boolean>(GLYPH_HEIGHT).fill(false));
      }
    }
  });
  return columns;
}
